// Regenerate the self-contained phone renderer after avatar artwork/code edits.
import { build } from 'vite';
import react from '@vitejs/plugin-react';
import { writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({ configFile: false, root, plugins: [react()], define: { 'import.meta.env.HARU_PHONE_AVATAR': true, 'process.env.NODE_ENV': '"production"' },
  build: { write: false, minify: true, lib: { entry: root + 'src/phoneAvatar.tsx', name: 'HaruPhoneAvatar', formats: ['iife'] } },
});
const code = (Array.isArray(result) ? result[0] : result).output.find(item => item.type === 'chunk').code;
const version = createHash('sha256').update(code).digest('hex').slice(0, 16);
const script = code.replaceAll('HARU_AVATAR_REVISION', version).replace(/<\/script/gi, '<\\/script');
await writeFile(root + 'build/lib/haru-avatar.js', script);
await writeFile(root + 'electron/avatarClient.ts', '// Generated by scripts/build-phone-avatar.mjs; regenerate instead of editing.\nexport const AVATAR_CLIENT_VERSION = ' + JSON.stringify(version) + ';\n');
console.log(`Phone avatar ${version}: ${Buffer.byteLength(script)} bytes, same renderer and artwork as desktop.`);
